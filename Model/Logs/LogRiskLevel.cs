namespace Model.Logs
{
    /// 日志风险等级（三级），用于区分日志的严重程度，前端可按等级过滤、报警。
    /// 数值越大风险越高，数据库里按整数存储，枚举名用于代码可读性。
    public enum LogRiskLevel
    {
        /// 低风险：正常流程留痕，如接口调用成功、PLC 连接成功、任务下发成功。
        /// 一般只做记录，不触发报警。
        Low = 1,

        /// 中风险：异常但可自行恢复或可被重试消除，如参数校验失败、单次读写超时后重连成功、设备暂未连接。
        /// 需要关注，但通常不中断生产。
        Medium = 2,

        /// 高风险：影响系统/设备正常运行的故障，如设备断线、连续读写失败、数据库不可用、未处理异常。
        /// 需要及时处理，可触发报警。
        High = 3
    }
}
